export function maxImposters(count: number): number {
  return Math.min(7, count - 1)
}

export function chooseImposters(names: string[], count: number): string[] {
  const pool = [...names]
  const picked: string[] = []
  for (let i = 0; i < count && pool.length > 0; i++) {
    const idx = Math.floor(Math.random() * pool.length)
    picked.push(pool.splice(idx, 1)[0])
  }
  return picked
}

export function pickAction(): string {
  return SECRET_ACTIONS[Math.floor(Math.random() * SECRET_ACTIONS.length)]
}

export function actionNumber(action: string): number {
  return SECRET_ACTIONS.indexOf(action) + 1
}

export function defaultNames(count: number): string[] {
  return Array.from({ length: count }, (_, i) => `اللاعب ${i + 1}`)
}

export function formatClock(totalSeconds: number): string {
  const m = Math.floor(totalSeconds / 60)
  const s = totalSeconds % 60
  return `${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`
}